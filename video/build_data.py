"""Turn a real demo run (capture/) into data.js for the video.

    uv run python video/capture.py      # re-run the demo, writes capture/demo_run.txt + demo_data.json
    python3 video/build_data.py         # writes video/data.js

Every number, hash, block and label the video shows comes from that run.
"""

import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
CAP = HERE / "capture"

# The 10 Imagenette classes, by ImageNet-1k index (MobileNetV2 outputs these).
CLASS_NAMES = {
    0: "tench", 217: "English springer", 482: "cassette player", 491: "chain saw", 497: "church",
    566: "French horn", 569: "garbage truck", 571: "gas pump", 574: "golf ball", 701: "parachute",
}


def scenario_blocks(text: str) -> dict[int, str]:
    parts = re.split(r"^={10,}\nScenario (\d): .*\n={10,}\n", text, flags=re.M)
    out = {int(parts[i]): parts[i + 1] for i in range(1, len(parts), 2)}
    out[5], tail = out[5].split("\nReputation counters", 1)
    out["tail"] = "Reputation counters" + tail
    return out


def parse_scenario(body: str) -> dict:
    log, timeline, balances, checks = [], [], [], []
    section = "log"
    for line in body.splitlines():
        s = line.strip()
        if not s:
            continue
        if s == "timeline:":
            section = "timeline"
            continue
        if s == "balances (ETH):":
            section = "balances"
            continue
        if s.startswith("[ok]") or s.startswith("[FAIL]"):
            checks.append(s)
            continue
        if section == "log" and (m := re.match(r"\[(\w+)\] (.*)", s)):
            log.append([m.group(1), m.group(2)])
        elif section == "log":
            log.append(["", s])
        elif section == "timeline" and (m := re.match(r"block\s+(\d+)\s+(.*)", s)):
            timeline.append([int(m.group(1)), m.group(2)])
        elif section == "balances" and not s.startswith("who"):
            cols = s.split()
            role = cols[1] if len(cols) == 7 else ""
            net, stake, dstake = cols[-5], cols[-2], cols[-1]
            balances.append({"who": cols[0], "role": role, "net": float(net),
                             "stake": None if stake == "-" else float(stake), "dstake": float(dstake)})
    return {"log": log, "timeline": timeline, "balances": balances, "checks": checks}


def main() -> None:
    text = (CAP / "demo_run.txt").read_text()
    data = json.loads((CAP / "demo_data.json").read_text())
    blocks = scenario_blocks(text)
    scenarios = {n: parse_scenario(blocks[n]) for n in range(1, 6)}

    commits = re.findall(r"^\s+(\d)\s+0\.040\s+200\s+A\s+(0x[0-9a-f]+)\.\.\.", blocks[2], flags=re.M)
    rep = []
    for line in blocks["tail"].splitlines()[2:]:
        cols = line.split()
        if len(cols) == 9 and cols[0] in "ABCDEF":
            rep.append([cols[0], float(cols[1]), *map(int, cols[2:])])

    jobs = {}
    for sc, j in data["jobs"].items():
        jobs[sc] = {k: j[k] for k in ("id", "main", "verifiers", "tiebreaker", "mismatched")}
        jobs[sc]["agents"] = {n: {k: v for k, v in a.items() if k in ("role", "slot", "cheated", "labels", "indices")}
                              for n, a in j["agents"].items()}

    out = {
        "header": [l.strip() for l in text.split("\n\n=")[0].splitlines()],
        "scenarios": scenarios,
        "verifyCommits": {int(a): b for a, b in commits},
        "reputation": rep,
        "images": data["images"],
        "expected": data["expected"],
        "classNames": CLASS_NAMES,
        "jobs": jobs,
        "demoLines": text.rstrip("\n").splitlines(),
        "forge": (CAP / "forge_test.txt").read_text().strip(),
        "pytest": (CAP / "pytest.txt").read_text().strip(),
    }
    (HERE / "data.js").write_text("// Generated by build_data.py from a real demo run. Do not edit.\n"
                                  "window.DATA = " + json.dumps(out, separators=(",", ":")) + ";\n")
    print(f"wrote data.js ({len(out['demoLines'])} demo lines, {len(rep)} providers)")


if __name__ == "__main__":
    main()
