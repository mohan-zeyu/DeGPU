"""Synthesize the voiceover with Kokoro (local, offline) and record each line's length.

    node video/render.mjs --narration                 # writes narration_lines.json
    video/.tts/venv/bin/python video/narrate.py       # writes voice/*.wav + narration_durations.js

Setup (once): a separate venv with kokoro-onnx, and the v1.0 model files in .tts/models/:
    uv venv --python 3.12 video/.tts/venv && VIRTUAL_ENV=video/.tts/venv uv pip install kokoro-onnx soundfile
    https://github.com/thewh1teagle/kokoro-onnx/releases/download/model-files-v1.0/kokoro-v1.0.onnx
    https://github.com/thewh1teagle/kokoro-onnx/releases/download/model-files-v1.0/voices-v1.0.bin

Lines whose text, voice and speed did not change are reused from voice/.
"""

import hashlib
import json
import subprocess
import sys
from pathlib import Path

import numpy as np
import soundfile as sf
from kokoro_onnx import Kokoro

HERE = Path(__file__).resolve().parent
MODELS = HERE / ".tts" / "models"
OUT = HERE / "voice"
VOICE = "af_heart"
SPEED = 1.0
SR_OUT = 44100
TARGET_RMS_DB = -20.0


def trim(x, sr):
    """Cut leading/trailing silence, keeping a short margin, with tiny fades."""
    env = np.convolve(np.abs(x), np.ones(int(0.01 * sr)) / int(0.01 * sr), "same")
    on = np.where(env > env.max() * 10 ** (-42 / 20))[0]
    a = max(0, on[0] - int(0.03 * sr))
    b = min(len(x), on[-1] + int(0.08 * sr))
    y = x[a:b].copy()
    f = int(0.01 * sr)
    y[:f] *= np.linspace(0, 1, f)
    y[-f:] *= np.linspace(1, 0, f)
    return y


def level(x, sr):
    """Scale to a common speech loudness (RMS of the voiced frames), peak-limited."""
    frames = x[: len(x) // 512 * 512].reshape(-1, 512)
    rms = np.sqrt((frames ** 2).mean(1))
    voiced = rms[rms > rms.max() * 0.1]
    gain = 10 ** (TARGET_RMS_DB / 20) / np.sqrt((voiced ** 2).mean())
    gain = min(gain, 10 ** (-1 / 20) / np.abs(x).max())
    return x * gain


def main():
    lines = json.loads((HERE / "narration_lines.json").read_text())
    OUT.mkdir(exist_ok=True)
    kokoro = Kokoro(str(MODELS / "kokoro-v1.0.onnx"), str(MODELS / "voices-v1.0.bin"))
    durations = {}
    made = 0
    for line in lines:
        key = hashlib.sha1(f"{VOICE}|{SPEED}|{line['say']}".encode()).hexdigest()[:12]
        wav = OUT / f"{line['id']}.wav"
        stamp = OUT / f"{line['id']}.key"
        if not (wav.exists() and stamp.exists() and stamp.read_text() == key):
            samples, sr = kokoro.create(line["say"], voice=VOICE, speed=SPEED, lang="en-us")
            y = level(trim(np.asarray(samples, dtype=np.float32), sr), sr)
            tmp = OUT / f"{line['id']}.24k.wav"
            sf.write(tmp, y, sr, subtype="FLOAT")
            subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(tmp), "-ar", str(SR_OUT), "-c:a", "pcm_s16le", str(wav)], check=True)
            tmp.unlink()
            stamp.write_text(key)
            made += 1
            print(f"  {line['id']:<10} {line['say'][:70]}", file=sys.stderr)
        durations[line["id"]] = round(sf.info(wav).duration, 3)
    for f in OUT.glob("*.wav"):  # drop lines that no longer exist
        if f.stem not in durations:
            f.unlink()
            f.with_suffix(".key").unlink(missing_ok=True)
    (HERE / "narration_durations.js").write_text(
        "// Generated by narrate.py: spoken length of each narration line (s).\n"
        "window.NARRATION_DURATIONS = " + json.dumps(durations, indent=1) + ";\n")
    total = sum(durations.values())
    print(f"{len(durations)} lines ({made} synthesized), {total:.0f} s of speech -> narration_durations.js")


if __name__ == "__main__":
    main()
